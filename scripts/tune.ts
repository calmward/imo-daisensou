// Calibrates each stage's difficulty factor against a simulated player's progression.
import { writeFileSync } from 'node:fs';
import { Battle } from '../src/game/battle';
import { simulate } from '../src/game/bot';
import { applyWin } from '../src/game/progress';
import { battleMods } from '../src/game/research';
import { newSave, type SaveData } from '../src/game/save';
import { chooseDeck, spendGold } from '../src/game/simCampaign';
import { STAGES } from '../src/game/stages';
import { TUNING } from '../src/game/tuning';

const SKILL = Number(process.env.SKILL ?? 0.6);
const LIMIT = (_id: number) => 420;
// "valley" stages are intentionally easy; bosses a bit harder
const VALLEY = new Set([9, 16, 21, 28, 34]);
function target(id: number) {
  const st = STAGES[id - 1];
  if (VALLEY.has(id)) return 0.55; // factor relative to the max-beatable factor
  if (st.boss) return 0.82;
  if (id <= 3) return 0.45;
  // slow sawtooth inside each world: rises towards boss
  const pos = ((id - 1) % 12) / 11;
  return 0.58 + 0.2 * pos;
}

function trial(save: SaveData, id: number, f: number, seed: number) {
  const base = STAGES[id - 1];
  const prev = TUNING[id - 1] ?? 1;
  const st = { ...base, spawns: base.spawns.map((s) => ({ ...s, mult: Math.round(((s.mult ?? 100) / prev) * f) })) };
  const b = new Battle(st, save.deck.map((d) => ({ id: d, level: save.units[d] })), battleMods(save.research), seed);
  return simulate(b, LIMIT(id), SKILL);
}

const save = newSave();
const out: number[] = [];
for (const st of STAGES) {
  chooseDeck(save);
  spendGold(save);
  // find the max factor the bot can still beat (2 of 2 seeds, within 300s)
  let lo = 0.2,
    hi = 4;
  for (let it = 0; it < 14; it++) {
    const mid = (lo + hi) / 2;
    const ok = [11, 23].every((sd) => trial(save, st.id, mid, sd).win);
    if (ok) lo = mid;
    else hi = mid;
  }
  let f = Math.round(lo * target(st.id) * 1000) / 1000;
  // keep battles short enough for kids: ~4 min max for bosses, ~3 min otherwise
  const cap = st.boss ? 240 : 190;
  for (let k = 0; k < 12; k++) {
    const ts = [11, 23].map((sd) => trial(save, st.id, f, sd).time);
    if (Math.max(...ts) <= cap) break;
    f = Math.round(f * 0.9 * 1000) / 1000;
  }
  out.push(f);
  const r = trial(save, st.id, f, 99);
  console.log(`${st.id} max=${lo.toFixed(2)} use=${f} win=${r.win} t=${r.time.toFixed(0)} base=${r.baseFrac.toFixed(2)} lv=${(save.deck.reduce((a, d) => a + save.units[d], 0) / save.deck.length).toFixed(1)}`);
  applyWin(save, st, 60);
  // kids replay a bit: one extra replay of the stage per stage cleared
  applyWin(save, st, 60);
}
writeFileSync('src/game/tuning.ts', `// Per-stage difficulty factors, generated by scripts/tune.ts (balance simulation).\nexport const TUNING: number[] = ${JSON.stringify(out)};\n`);
